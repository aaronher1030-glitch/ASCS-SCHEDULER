from __future__ import annotations

from datetime import datetime
from enum import Enum

from pydantic import BaseModel, Field


class EntryStatus(str, Enum):
    pending = "pending"
    finalized = "finalized"
    manual = "manual"


class ScheduleEntryBase(BaseModel):
    subject_id: int
    faculty_id: int | None = None
    room_id: int | None = None
    section_name: str = Field(min_length=1, max_length=100)
    day_of_week: int = Field(ge=0, le=4)   # 0=Mon … 4=Fri
    time_slot: int = Field(ge=1, le=12)    # period number
    status: EntryStatus = EntryStatus.pending


class ScheduleEntryCreateRequest(ScheduleEntryBase):
    tenant_id: str = Field(default="default-tenant", max_length=120)
    job_id: str | None = None


class ScheduleEntryUpdateRequest(BaseModel):
    faculty_id: int | None = None
    room_id: int | None = None
    day_of_week: int | None = Field(default=None, ge=0, le=4)
    time_slot: int | None = Field(default=None, ge=1, le=12)
    status: EntryStatus | None = None


class ScheduleEntryResponse(ScheduleEntryBase):
    id: int
    job_id: str | None
    tenant_id: str
    created_at: datetime

    model_config = {"from_attributes": True}


class BulkFinalizeRequest(BaseModel):
    """Finalize (or reset) all pending entries for a given job."""
    job_id: str
    action: str = Field(pattern="^(finalize|reset)$")


class BulkCreateRequest(BaseModel):
    """Bulk-insert a batch of entries generated by the solver."""
    entries: list[ScheduleEntryCreateRequest] = Field(min_length=1)
